void main() {
  String firstText = '25';
  String secondText = '17';

  int first = int.parse(firstText);
  int second = int.parse(secondText);
  int sum = first + second;

  print('=== STRING TO NUMBER ===');
  print('First: $first');
  print('Second: $second');
  print('Sum: $first + $second = $sum');
}